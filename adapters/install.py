#!/usr/bin/env python3
"""Підключає personal-AI-config до Claude Code (і, за запитом, до Codex).

    python adapters/install.py            # встановити/оновити адаптери Claude
    python adapters/install.py --check    # лише показати стан, нічого не змінювати
    python adapters/install.py --home DIR # використати DIR замість домашнього каталогу (тест)
    python adapters/install.py --codex-only --check  # Codex: лише перевірка
    python adapters/install.py --codex-only --prepare PLAN.json  # без активації

Ідемпотентний: правильні посилання й блоки пропускаються; чужі файли та
посилання не змінюються (повідомляється конфлікт). Нічого не видаляє.
Шляхи визначаються під час запуску; у репозиторії абсолютних шляхів немає.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
GLOBAL = REPO / "global"
LINK_NAME = "personal-ai-config"
BEGIN = "<!-- personal-ai-config:begin (generated by adapters/install.py; do not edit inside) -->"
END = "<!-- personal-ai-config:end -->"
HOOK_MARKER = "private_context.py"
GENERATED = "GENERATED by personal-ai-config/adapters/install.py — edit global/ in the private repo, then re-run install."


class Report:
    def __init__(self, check):
        self.check = check
        self.problems = 0

    def ok(self, msg):
        print(f"  ok        {msg}")

    def todo(self, msg):
        print(f"  {'missing' if self.check else 'create':<9} {msg}")
        if self.check:
            self.problems += 1

    def conflict(self, msg):
        print(f"  CONFLICT  {msg}")
        self.problems += 1


def posix(path):
    return str(path).replace("\\", "/")


def display_path(path, home):
    """~/… для шляхів у домашньому каталозі (переносимо між машинами), інакше абсолютний."""
    try:
        return "~/" + posix(Path(path).resolve().relative_to(Path(home).resolve()))
    except ValueError:
        return posix(Path(path).resolve())


def same(a, b):
    return os.path.normcase(os.path.realpath(a)) == os.path.normcase(os.path.realpath(b))


def make_dir_link(link, target):
    link.parent.mkdir(parents=True, exist_ok=True)
    if os.name == "nt":
        # Junction не потребує прав адміністратора чи Developer Mode.
        out = subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(target)],
                             capture_output=True, text=True)
        if out.returncode != 0:
            raise OSError(out.stderr.strip() or out.stdout.strip())
    else:
        os.symlink(target, link, target_is_directory=True)


def ensure_link(rep, link, target):
    if os.path.lexists(link):
        if same(link, target):
            rep.ok(f"{link} -> {target}")
        else:
            rep.conflict(f"{link} існує і не вказує на {target}; не змінюю")
        return
    rep.todo(f"{link} -> {target}")
    if not rep.check:
        make_dir_link(link, target)


def write_text(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def backup(path):
    dst = path.with_name(f"{path.name}.bak-{time.strftime('%Y%m%d-%H%M%S')}")
    shutil.copy2(path, dst)
    return dst


def ensure_block(rep, path, block):
    """Оновлює лише маркерний блок; файл без маркерів не чіпає, якщо він непорожній."""
    full = f"{BEGIN}\n{block.rstrip()}\n{END}\n"
    if not path.exists():
        rep.todo(f"{path} (новий файл з блоком personal-ai-config)")
        if not rep.check:
            write_text(path, full)
        return
    text = path.read_text(encoding="utf-8")
    if BEGIN in text and END in text:
        start, end = text.index(BEGIN), text.index(END) + len(END)
        current = text[start:end] + "\n"
        if current == full:
            rep.ok(f"{path} (блок актуальний)")
            return
        rep.todo(f"{path} (оновити блок personal-ai-config)")
        if not rep.check:
            backup(path)
            write_text(path, text[:start] + full.rstrip("\n") + text[end:])
        return
    if text.strip():
        rep.conflict(f"{path} існує без маркерів; додайте вручну:\n{full}")
        return
    rep.todo(f"{path} (порожній файл → блок)")
    if not rep.check:
        write_text(path, full)


def ensure_hook(rep, settings_path, command):
    entry = {"hooks": [{"type": "command", "command": command, "timeout": 15}]}
    data = {}
    if settings_path.exists():
        raw = settings_path.read_text(encoding="utf-8")
        try:
            data = json.loads(raw) if raw.strip() else {}
        except ValueError:
            rep.conflict(f"{settings_path}: невалідний JSON; не змінюю")
            return
    groups = data.get("hooks", {}).get("SessionStart", [])
    ours = [h for g in groups for h in g.get("hooks", []) if HOOK_MARKER in h.get("command", "")]
    if ours:
        if any(h.get("command") == command for h in ours):
            rep.ok(f"{settings_path}: SessionStart hook")
        else:
            rep.conflict(f"{settings_path}: SessionStart hook personal-ai-config має іншу команду; "
                         f"очікується: {command}")
        return
    rep.todo(f"{settings_path}: додати SessionStart hook")
    if rep.check:
        return
    if settings_path.exists():
        print(f"            бекап: {backup(settings_path)}")
    data.setdefault("hooks", {}).setdefault("SessionStart", []).append(entry)
    write_text(settings_path, json.dumps(data, indent=2, ensure_ascii=False) + "\n")


def ensure_git_hooks(rep):
    try:
        out = subprocess.run(["git", "-C", str(REPO), "config", "--local", "--get", "core.hooksPath"],
                             capture_output=True, text=True)
    except OSError:
        rep.conflict("git не знайдено; pre-commit не підключено")
        return
    current = out.stdout.strip()
    if current == ".githooks":
        rep.ok("git core.hooksPath = .githooks (приватне репо)")
    elif current:
        rep.conflict(f"git core.hooksPath = {current}; не змінюю")
    else:
        rep.todo("git core.hooksPath = .githooks (локальний config приватного репо)")
        if not rep.check:
            subprocess.run(["git", "-C", str(REPO), "config", "--local", "core.hooksPath", ".githooks"], check=True)


def skills():
    return sorted(p.parent for p in (GLOBAL / "skills").glob("*/SKILL.md"))


def parse_agent(path):
    text = path.read_text(encoding="utf-8")
    m = re.match(r"^---\n(.*?)\n---\n?(.*)$", text, re.S)
    if not m:
        raise ValueError(f"{path}: немає frontmatter")
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t")):
            k, _, v = line.partition(":")
            meta[k.strip()] = v.strip()
    return meta, m.group(2).strip()


def toml_str(value):
    return json.dumps(value, ensure_ascii=False)


def install_claude(rep, home, python):
    claude = home / ".claude"
    print(f"Claude Code ({claude}):")
    for skill in skills():
        ensure_link(rep, claude / "skills" / skill.name, skill)
    ensure_link(rep, claude / "agents" / LINK_NAME, GLOBAL / "agents")
    ensure_link(rep, claude / "rules" / LINK_NAME, GLOBAL / "rules")

    root = display_path(REPO, home)
    ensure_block(rep, claude / "CLAUDE.md", "\n".join([
        f"AI_PRIVATE_ROOT = {root}",
        "Глобальні правила (імпорт — зміни в global/AGENTS.md діють без перевстановлення):",
        "",
        f"@{root}/global/AGENTS.md",
    ]))

    command = f'"{posix(python)}" "{posix(GLOBAL / "hooks" / "private_context.py")}" --private-root "{posix(REPO)}"'
    ensure_hook(rep, claude / "settings.json", command)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    operation = parser.add_mutually_exclusive_group()
    operation.add_argument("--check", action="store_true", help="лише перевірити стан")
    operation.add_argument("--prepare", metavar="PLAN", help="Codex: записати план, не активувати")
    operation.add_argument("--activate", metavar="PLAN", help="Codex: застосувати погоджений план")
    operation.add_argument("--rollback", metavar="MANIFEST", help="Codex: відновити стан за manifest")
    parser.add_argument("--home", help="домашній каталог (за замовчуванням — поточного користувача)")
    parser.add_argument("--codex-only", "--codex", dest="codex", action="store_true",
                        help="лише Codex; без операції — попередній перегляд")
    parser.add_argument("--codex-home", help="явний Codex home; інакше CODEX_HOME або ~/.codex")
    parser.add_argument("--replace", action="append", default=[], metavar="OBJECT",
                        help="план міграції лише AGENTS.md або skill:private-project-memory")
    parser.add_argument("--python", default=sys.executable, help="інтерпретатор для hook")
    args = parser.parse_args()
    sys.stdout.reconfigure(encoding="utf-8")
    sys.dont_write_bytecode = True
    if args.codex:
        if (args.activate or args.rollback) and (args.home or args.codex_home or args.replace):
            parser.error("activation/rollback use paths and approvals from the reviewed plan/manifest")
        from codex.adapter import run
        try:
            return run(args, REPO)
        except (ValueError, OSError, KeyError, TypeError) as exc:
            print("Codex adapter: " + str(exc), file=sys.stderr)
            return 1
    if args.prepare or args.activate or args.rollback or args.codex_home or args.replace:
        parser.error("Codex operations require --codex-only")

    home = Path(args.home).resolve() if args.home else Path.home()
    rep = Report(args.check)
    print(f"personal-AI-config: {REPO}")
    print(f"home: {home}{'  [CHECK — без змін]' if args.check else ''}")

    install_claude(rep, home, args.python)
    print("Приватне репо:")
    if args.home:
        print("  skip      core.hooksPath (тестовий режим --home не змінює конфіг репозиторію)")
    else:
        ensure_git_hooks(rep)

    if rep.problems:
        print(f"Проблем/відсутніх елементів: {rep.problems}")
        return 1
    print("Готово." if not args.check else "Усе на місці.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
